// Run against the production frontend: PWA_TEST_URL=http://127.0.0.1:3000 node new-tests/pwa/offline-attendance-browser.mjs
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(`${process.env.PWA_TEST_DEPENDENCIES ?? '/private/tmp/saiv-pwa-tests'}/package.json`);
const { chromium } = require('playwright-core');
const origin = process.env.PWA_TEST_URL ?? 'http://127.0.0.1:3000';
const browser = await chromium.launch({ executablePath: process.env.PWA_BROWSER_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true });
  const now = Date.now();
  const session = (id, name, deadline, end) => ({ id, name, status: 'active', course_code: 'SC3099', scheduled_start: new Date(now - 3600000).toISOString(), scheduled_end: new Date(end).toISOString(), checkin_opens_at: new Date(now - 3600000).toISOString(), checkin_closes_at: new Date(deadline).toISOString(), venue_name: 'Lecture room' });
  const open = session('open', 'Open seminar', now + 600000, now + 3600000);
  const recent = session('recent', 'Recent lecture', now - 600000, now + 7200000);
  const expired = session('expired', 'Ended lecture', now - 7200000, now - 3600000);
  let records = [{ id: 'c-open', session_id: 'open', status: 'approved', checked_in_at: new Date(now - 1000).toISOString(), risk_score: 0.2 },
    { id: 'c-recent', session_id: 'recent', status: 'flagged', checked_in_at: new Date(now - 1800000).toISOString(), risk_score: 0.8 }];
  let unreachable = false, windowClosed = false, submissions = 0;
  await context.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url());
    if (unreachable === 'gateway') return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Service temporarily unavailable' }) });
    if (unreachable) return route.abort('internetdisconnected');
    let body = {};
    if (url.pathname.endsWith('/auth/refresh')) body = { access_token: 'offline-test-token' };
    else if (url.pathname.endsWith('/users/me')) body = { id: 'offline-student', full_name: 'Test Student', email: 'test@example.com', role: 'student', camera_consent: true, geolocation_consent: true };
    else if (url.pathname.endsWith('/sessions/active')) body = windowClosed ? [] : [open];
    else if (url.pathname.endsWith('/sessions/my-sessions')) body = [open, recent, expired];
    else if (url.pathname.endsWith('/checkins/my-checkins')) body = records.filter(record => !url.searchParams.has('session_id') || record.session_id === url.searchParams.get('session_id'));
    else if (url.pathname.endsWith('/devices/my-devices')) body = [];
    else if (url.pathname.endsWith('/devices/registration-challenges')) body = { challenge_id: 'test', challenge: 'test-challenge' };
    else if (url.pathname.endsWith('/devices/register')) body = { ...route.request().postDataJSON(), id: 'device', is_active: true, browser_identity_verified: true };
    else if (url.pathname.endsWith('/push/config')) body = { enabled: false, public_key: null };
    if (url.pathname.endsWith('/checkins/') && route.request().method() === 'POST') submissions++;
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) });
  });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/attendance`);
  await page.getByRole('heading', { name: 'Open seminar', exact: true }).waitFor();
  await page.evaluate(() => navigator.serviceWorker.ready);
  const savedStatus = async (id, expected) => page.waitForFunction(({ id, expected }) => new Promise(resolve => {
    const request = indexedDB.open('saiv-offline', 2);
    request.onsuccess = () => {
      const db = request.result;
      const read = db.transaction('session-snapshots').objectStore('session-snapshots').get('active-sessions:offline-student');
      read.onsuccess = () => { db.close(); resolve(read.result?.sessions.some(session => session.id === id && session.attendance?.status === expected)); };
    };
  }), { id, expected });
  await savedStatus('recent', 'flagged');
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('heading', { name: 'Saved sessions', exact: true }).waitFor();
  await page.getByText('Offline', { exact: true }).waitFor();
  const dropdown = page.getByLabel('Saved session', { exact: true });
  await dropdown.waitFor();
  assert.equal(await dropdown.locator('option').count(), 2);
  assert.equal(await dropdown.locator('option', { hasText: 'Ended lecture' }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /My check-ins|Sessions \(/ }).count(), 0);
  await page.getByRole('heading', { name: 'Attendance confirmed', exact: true }).waitFor();
  await page.getByText('0.20', { exact: true }).waitFor();
  await dropdown.selectOption('recent');
  await page.getByRole('heading', { name: 'Recent lecture', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Submitted for review', exact: true }).waitFor();
  await page.getByText('0.80', { exact: true }).waitFor();
  await page.getByText('Lecture room', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Submit check-in', exact: true }).count(), 0);
  await page.screenshot({ path: '/private/tmp/saiv-offline-mobile.png', fullPage: true });
  console.log('PASS offline reload: statuses survive closed check-in windows, expired sessions hidden, dropdown switches result and risk score');
  unreachable = true;
  await context.setOffline(false);
  await page.getByText('Connection unavailable — saved sessions only', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => navigator.onLine), true);
  console.log('PASS network failure with navigator.onLine=true: labelled offline snapshot');
  unreachable = 'gateway';
  await page.getByRole('button', { name: 'Retry connection', exact: true }).click();
  await page.getByText('Connection unavailable — saved sessions only', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Retry connection', exact: true }).waitFor();
  console.log('PASS temporary gateway outage remains a labelled offline view');
  unreachable = false; windowClosed = true;
  records = records.map(record => ({ ...record, status: 'approved' }));
  await page.getByRole('button', { name: 'Retry connection', exact: true }).click();
  await page.getByRole('heading', { name: 'No active sessions', exact: true }).waitFor();
  await savedStatus('recent', 'approved');
  await context.setOffline(true);
  await page.getByRole('heading', { name: 'Saved sessions', exact: true }).waitFor();
  await page.getByLabel('Saved session', { exact: true }).selectOption('recent');
  await page.getByRole('heading', { name: 'Recent lecture', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Attendance confirmed', exact: true }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Submitted for review', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Sign out and clear saved sessions', exact: true }).click();
  await page.getByRole('tab', { name: 'Sign in', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('saiv-offline-owner')), null);
  assert.equal(submissions, 0);
  assert.deepEqual(errors, []);
  console.log('PASS reconnect refreshes approval, empty active list retains unended sessions, logout clears cache, no offline submissions');
} finally { await browser.close(); }
